# app.tenant_id is set per transaction by tenant_session() (set_config(..., true)). When it is
# not set, current_setting(..., true) is NULL - or '' on a pooled connection that used it before;
# nullif() turns both into NULL, so the policy matches zero rows (fail closed, R16).
_CURRENT_TENANT = "nullif(current_setting('app.tenant_id', true), '')::uuid"


# 🔒 For every tenant table: rows are visible only when tenant_id matches app.tenant_id.
def _enable_row_level_security() -> None:
    for table, column in [("tenants", "id"), *((t, "tenant_id") for t in TENANT_TABLES)]:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        # FORCE: the table owner is subject to the policy too (only BYPASSRLS roles skip it).
        op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
        op.execute(
            f"CREATE POLICY tenant_isolation ON {table} "
            f"USING ({column} = {_CURRENT_TENANT}) "
            f"WITH CHECK ({column} = {_CURRENT_TENANT})"
        )


# --- widget public-key lookup (R24 exception, P1.11) ----------------------------------------


# 🔒 The only way to find a bot by its public widget key before a tenant is known.
def _create_public_key_lookup() -> None:
    # Runs before a tenant context exists. Returns two ids and nothing else, so it can't be used
    # to read tenant data. SECURITY DEFINER runs as the owner (a BYPASSRLS role on Supabase, the
    # superuser locally); search_path is pinned so it can't be hijacked.
    op.execute(
        """
        CREATE FUNCTION resolve_bot_public_key(p_key text)
        RETURNS TABLE (tenant_id uuid, bot_id uuid)
        LANGUAGE sql STABLE SECURITY DEFINER
        SET search_path = public, pg_temp
        AS $$
            SELECT b.tenant_id, b.id FROM public.bots b WHERE b.public_key = p_key
        $$
        """
    )
    op.execute("REVOKE ALL ON FUNCTION resolve_bot_public_key(text) FROM PUBLIC")


