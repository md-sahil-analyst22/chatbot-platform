# app.tenant_id is set per transaction by tenant_session() (set_config(..., true)). When it is
# not set, current_setting(..., true) is NULL - or '' on a pooled connection that used it before;
# nullif() turns both into NULL, so the policy matches zero rows (fail closed, R16).
_CURRENT_TENANT = "nullif(current_setting('app.tenant_id', true), '')::uuid"


# 🔒 For every tenant table: rows are visible only when tenant_id matches app.tenant_id.
def _enable_row_level_security() -> None:
    # For `tenants` (matched on its id) and every tenant table (matched on tenant_id)...
    for table, column in [("tenants", "id"), *((t, "tenant_id") for t in TENANT_TABLES)]:
        # ...switch on row-level security,
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        # FORCE: the table owner is subject to the policy too (only BYPASSRLS roles skip it).
        op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
        # ...and add the policy: a row is visible and writable only when its tenant matches
        #   app.tenant_id.
        op.execute(
            f"CREATE POLICY tenant_isolation ON {table} "
            f"USING ({column} = {_CURRENT_TENANT}) "
            f"WITH CHECK ({column} = {_CURRENT_TENANT})"
        )


# --- widget public-key lookup (R24 exception, P1.11) ----------------------------------------


# 🔒 The only way to find a bot by its public widget key before a tenant is known.
def _create_public_key_lookup() -> None:
    # Runs before a tenant context exists. Returns two ids and nothing else, so it can't be used
    # to read tenant data. SECURITY DEFINER runs as the owner (a BYPASSRLS role on Supabase, the
    # superuser locally); search_path is pinned so it can't be hijacked.
    op.execute(
        """
        CREATE FUNCTION resolve_bot_public_key(p_key text)
        RETURNS TABLE (tenant_id uuid, bot_id uuid)
        LANGUAGE sql STABLE SECURITY DEFINER
        SET search_path = public, pg_temp
        AS $$
            SELECT b.tenant_id, b.id FROM public.bots b WHERE b.public_key = p_key
        $$
        """
    )
    # 🔒 Nobody may call the function by default (saathi_app is allowed below).
    op.execute("REVOKE ALL ON FUNCTION resolve_bot_public_key(text) FROM PUBLIC")


# --- privileges (R24) -------------------------------------------------------------------------


# 🔒 Least privilege: the app may read/write rows, but never change tables, and never edit the
# audit log.
def _apply_privileges() -> None:
    tables = ", ".join(("tenants", *TENANT_TABLES))  # module constants, never user input
    # Run this block of SQL: grant saathi_app read/write on the tables (never table changes),
    #   make audit_logs append-only, hide Alembic's bookkeeping table, and allow calling the
    #   lookup function. Each step runs only if that role exists.
    op.execute(
        f"""
        DO $$
        BEGIN
            -- The app role: read/write rows only, never DDL; RLS applies (NOBYPASSRLS).
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'saathi_app') THEN
                GRANT SELECT, INSERT, UPDATE, DELETE ON {tables} TO saathi_app;
                -- Audit trail is append-only for the app.
                REVOKE UPDATE, DELETE ON audit_logs FROM saathi_app;
                -- Only migrations may touch the migration bookkeeping.
                IF to_regclass('public.alembic_version') IS NOT NULL THEN
                    REVOKE ALL ON alembic_version FROM saathi_app;
                END IF;
                GRANT EXECUTE ON FUNCTION resolve_bot_public_key(text) TO saathi_app;
            END IF;

            -- Supabase exposes the public schema through its Data API and grants these roles
            -- access by default. This backend never uses the Data API: take that access away.
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
                REVOKE ALL ON {tables} FROM anon, authenticated;
                REVOKE ALL ON FUNCTION resolve_bot_public_key(text) FROM anon, authenticated;
                IF to_regclass('public.alembic_version') IS NOT NULL THEN
                    REVOKE ALL ON alembic_version FROM anon, authenticated;
                END IF;
            END IF;
        END
        $$
        """  # noqa: S608  (only module-constant table names are interpolated)
    )
